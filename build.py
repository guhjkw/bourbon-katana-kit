# build.py: writes src/samples.js from samples/*.csv so the page's "Try it with sample files" button and the
# sample CSVs people can download are the same data (one source). Run after editing a sample: python3 build.py
import json, os
here = os.path.dirname(os.path.abspath(__file__))
files = {'items': 'sos-items-SAMPLE.csv', 'bom': 'sos-assemblies-SAMPLE.csv', 'orders': 'wholesale-orders-SAMPLE.csv'}
out = {k: {'name': f, 'text': open(os.path.join(here, 'samples', f), encoding='utf-8').read()} for k, f in files.items()}
open(os.path.join(here, 'src', 'samples.js'), 'w', encoding='utf-8').write('// src/samples.js: generated by build.py from samples/*.csv (invented data). Do not edit by hand.\nwindow.KIT_SAMPLES = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n')
print('wrote src/samples.js')
